/// Safe, idempotent, development-only data seeder for PayNest.
/// Populates an extensive dataset of 120+ Uganda-specific products, 110+ customers,
/// and 125+ historical transactions, with high-performance batch synchronization to Firebase.
class DevDataSeeder {
  static final DevDataSeeder instance = DevDataSeeder._();
  DevDataSeeder._();

  final DatabaseHelper _dbHelper = DatabaseHelper.instance;
  final FirestoreService _firestoreService = FirestoreService();

  /// Check whether development seed data is already loaded in SQLite (over 100 products)
  Future<bool> isSeeded() async {
    try {
      final db = await _dbHelper.database;
      final result = await db.rawQuery(
        "SELECT COUNT(*) as count FROM products WHERE id LIKE 'seed_p_%'",
      );
      final count = (result.first['count'] as int?) ?? 0;
      return count >= 100;
    } catch (e) {
      debugPrint('[DevDataSeeder] Error checking seed state: $e');
      return false;
    }
  }

  /// Populate the local SQLite database with over 100 products, customers, and transactions,
  /// and automatically synchronizes to Firebase Cloud Firestore if initialized.
  Future<void> seedAll({bool force = false}) async {
    final db = await _dbHelper.database;

    if (!force && await isSeeded()) {
      debugPrint('[DevDataSeeder] Database already populated with over 100 records. Checking cloud sync.');
      if (FirebaseService.instance.isInitialized) {
        await syncAllToFirebase();
      }
      return;
    }

    debugPrint('[DevDataSeeder] Seeding massive Uganda POS dataset (125+ products, 110+ customers, 125+ transactions)...');

    // First, clean out any old placeholder products/customers from the initial DB seed
    await db.delete('products', where: "id IN ('p1','p2','p3','p4','p5','p6','p7','p8')");
    await db.delete('customers', where: "id IN ('c1','c2','c3')");

    await db.transaction((txn) async {
      await _seedCategories(txn);
      await _seedProducts(txn);
      await _seedCustomers(txn);
      await _seedTransactions(txn);
    });

    debugPrint('[DevDataSeeder] Local dataset successfully seeded with 100+ of everything.');

    // Sync to Firebase if available
    if (FirebaseService.instance.isInitialized) {
      await syncAllToFirebase();
    }
  }

  /// Synchronize all local SQLite data (products, customers, transactions) to Firestore
  Future<int> syncAllToFirebase() async {
    if (!FirebaseService.instance.isInitialized) {
      debugPrint('[DevDataSeeder] Firebase is not initialized. Skipping Firebase upload.');
      return 0;
    }

    try {
      debugPrint('[DevDataSeeder] Uploading all local data to Firebase Cloud Firestore in batches...');
      final productRepo = ProductRepository();
      final customerRepo = CustomerRepository();
      final txnRepo = TransactionRepository();

      final products = await productRepo.getAllProducts();
      final customers = await customerRepo.getAllCustomers();
      final transactions = await txnRepo.getAllTransactions();

      final count = await _firestoreService.syncAllLocalDataToFirestore(
        products: products,
        customers: customers,
        transactions: transactions,
      );
      debugPrint('[DevDataSeeder] Successfully synchronized $count items to Firebase!');
      return count;
    } catch (e) {
      debugPrint('[DevDataSeeder] Error syncing seed data to Firebase: $e');
      return 0;
    }
  }

